def _tax_text() -> str:
    parts, low = [], 0
    for limit, rate in R.TAX_BRACKETS:
        if limit is None:
            parts.append(f"свыше {low} м. — {pct(rate)}%")
        else:
            parts.append(f"до {limit} м. — {pct(rate)}%")
            low = limit
    return ", ".join(parts)

